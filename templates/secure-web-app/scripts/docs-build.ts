export interface GeneratedDoc {
  path: string;
  content: string;
}

export async function generateDocs(): Promise<GeneratedDoc[]> {
  openDb(':memory:');
  try {
    runMigrations();
    await createApp();
    const ai = await loadAiModules();
    const routes = summariseRoutes();
    const schemas = routeSchemasAsJson();
    const pkg = JSON.parse(readFileSync(resolve(APP_ROOT, 'package.json'), 'utf8')) as PackageJson;
    const inventory = JSON.parse(readFileSync(resolve(APP_ROOT, 'crypto-inventory.json'), 'utf8')) as CryptoInventory;

    const docs: GeneratedDoc[] = [
      { path: 'authorization.md', content: genAuthorizationMd(routes) },
      { path: 'validation.md', content: genValidationMd(routes, schemas) },
      { path: 'sessions.md', content: genSessionsMd() },
      { path: 'SECURITY.md', content: genSecurityMd() },
      { path: 'crypto.md', content: genCryptoMd(inventory) },
      { path: 'logging.md', content: genLoggingMd() },
      { path: 'communications.md', content: genCommunicationsMd() },
      { path: 'uploads.md', content: genUploadsMd() },
      { path: 'data-protection.md', content: genDataProtectionMd() },
      { path: 'dependencies.md', content: genDependenciesMd(pkg) },
      { path: 'api.md', content: genApiMd(routes) },
      { path: 'openapi.json', content: `${JSON.stringify(genOpenApi(routes, schemas), null, 2)}\n` },
      { path: 'ai.md', content: ai ? genAiMd(ai) : genAiMdAbsent() },
      { path: 'deployment.md', content: genDeploymentMd() },
      { path: 'incident-response.md', content: genIncidentResponseMd() },
      { path: 'data-retention.md', content: genDataRetentionMd() },
    ];
    for (const adr of genAdrFiles()) docs.push({ path: `adr/${adr.file}`, content: adr.content });
    return docs;
  } finally {
    closeDb();
  }
}

function hash(text: string): string {
  return createHash('sha256').update(text).digest('hex');
}

async function main(): Promise<void> {
  const checkOnly = process.argv.includes('--check');
  const docs = await generateDocs();
  mkdirSync(resolve(DOCS_DIR, 'adr'), { recursive: true });

  if (checkOnly) {
    const stale: string[] = [];
    for (const d of docs) {
      const file = resolve(DOCS_DIR, d.path);
      const current = existsSync(file) ? readFileSync(file, 'utf8') : undefined;
      if (current === undefined || hash(current) !== hash(d.content)) stale.push(d.path);
    }
    if (stale.length === 0) {
      process.stdout.write(`docs/ is up to date with the code (${docs.length} files checked).\n`);
      return;
    }
    process.stdout.write(`docs/ is out of date. Run "npm run docs:build" to refresh:\n${stale.map((s) => `  - docs/${s}`).join('\n')}\n`);
    process.exitCode = 1;
    return;
  }

  for (const d of docs) {
    const file = resolve(DOCS_DIR, d.path);
    mkdirSync(dirnameOf(file), { recursive: true });
    writeFileSync(file, d.content);
  }
  process.stdout.write(`Wrote ${docs.length} files to docs/\n`);
}

function dirnameOf(file: string): string {
  return file.slice(0, Math.max(file.lastIndexOf('/'), 0));
}

const isMain = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  main().catch((err: Error) => {
    process.stderr.write(`\nCould not build the docs.\n${err.message}\n${err.stack ?? ''}\n\n`);
    process.exitCode = 1;
  });
}

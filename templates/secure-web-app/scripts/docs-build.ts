function formatBytes(n: number): string {
  if (n >= 1024 * 1024) {
    const mb = n / (1024 * 1024);
    return `${Number.isInteger(mb) ? mb : mb.toFixed(1)} MB`;
  }
  if (n >= 1024) return `${Math.round(n / 1024)} KB`;
  return `${n} bytes`;
}

function table(headers: string[], rows: string[][]): string {
  const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const head = `| ${headers.join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => `| ${r.map(esc).join(' | ')} |`).join('\n');
  return rows.length > 0 ? `${head}\n${sep}\n${body}` : `${head}\n${sep}\n| ${headers.map(() => '—').join(' | ')} |`;
}

function pathToOpenApi(path: string): string {
  return path.replace(/:([A-Za-z0-9_]+)/g, '{$1}');
}

function ownerText(r: RouteSummary): string {
  if (!r.owner) return '—';
  return `Must own the \`${r.owner.entity}\` record named by \`:${r.owner.param}\` (administrators may access any record).`;
}

function whoText(r: RouteSummary): string {
  if (r.auth === 'public') return 'Anyone (no sign-in required)';
  if (r.auth === 'user') return r.roles.length > 0 ? `Signed in, role ${r.roles.map((x) => `\`${x}\``).join(' or ')} (or an administrator)` : 'Any signed-in user';
  return `Role \`${r.auth.slice(5)}\` (or an administrator)`;
}

const PAGE = 'This file is generated by `npm run docs:build` from the app’s own code and configuration. Do not edit it by hand — change the code or configuration and run `npm run docs:build` again.';

function doc(title: string, intro: string, body: string): string {
  return `# ${title}\n\n${intro}\n\n${body}\n\n---\n\n*${PAGE}*\n`;
}


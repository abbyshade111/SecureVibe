function genValidationMd(routes: RouteSummary[], schemas: ReturnType<typeof routeSchemasAsJson>): string {
  const byRoute = new Map(schemas.map((s) => [`${s.method} ${s.path}`, s]));
  const sections = routes
    .filter((r) => !r.path.startsWith('/__securevibe'))
    .map((r) => {
      const s = byRoute.get(`${r.method} ${r.path}`);
      const parts: string[] = [`### ${r.method} \`${r.path}\``];
      const any = s && (s.params || s.query || s.body);
      if (!any) {
        parts.push('No fields are accepted beyond the path itself.');
      } else {
        if (s?.params) parts.push(`**Path parameters**\n\n\`\`\`json\n${JSON.stringify(s.params, null, 2)}\n\`\`\``);
        if (s?.query) parts.push(`**Query string**\n\n\`\`\`json\n${JSON.stringify(s.query, null, 2)}\n\`\`\``);
        if (s?.body) parts.push(`**Request body**\n\n\`\`\`json\n${JSON.stringify(s.body, null, 2)}\n\`\`\``);
      }
      return parts.join('\n\n');
    });
  return doc(
    'What every route accepts',
    [
      'Every route validates its input against a strict schema on the server before any of your data reaches the handler.',
      'A field that is not listed here is rejected — the app never silently ignores or guesses at an unexpected field, and it never accepts a list where a single value is expected.',
      'The schemas below are shown as JSON Schema, generated straight from the validation rules in the code.',
    ].join(' '),
    sections.join('\n\n'),
  );
}


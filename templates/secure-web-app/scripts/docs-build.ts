interface AdrOut {
  file: string;
  content: string;
}

function slug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60) || 'decision';
}

function genAdrFiles(): AdrOut[] {
  const designAdrs = config.design.adrs;
  if (designAdrs.length > 0) {
    return designAdrs.map((a, i) => ({
      file: `${String(i + 1).padStart(4, '0')}-${slug(a.title)}.md`,
      content: doc(
        `ADR ${i + 1}: ${a.title}`,
        `Status: ${a.status}${a.date ? ` · ${a.date}` : ''}`,
        [
          ['## Context', a.context || '*(not recorded)*'].join('\n\n'),
          ['## Decision', a.decision || '*(not recorded)*'].join('\n\n'),
          a.alternatives.length > 0 ? `## Alternatives considered\n\n${a.alternatives.map((x) => `- ${x}`).join('\n')}` : '',
          ['## Consequences', a.consequences || '*(not recorded)*'].join('\n\n'),
          a.relatedControls.length > 0 ? `Related SbD controls: ${a.relatedControls.map((c) => `\`${c}\``).join(', ')}` : '',
          a.relatedRequirements.length > 0 ? `Related requirements: ${a.relatedRequirements.map((c) => `\`${c}\``).join(', ')}` : '',
        ]
          .filter(Boolean)
          .join('\n\n'),
      ),
    }));
  }
  // No design was supplied (the template is being inspected on its own): document the baseline's own decisions.
  const baseline: { title: string; context: string; decision: string; consequences: string }[] = [
    {
      title: 'Built-in node:sqlite instead of a native database driver',
      context: 'The app needs a local database with zero native compilation, so that `npm install --ignore-scripts` is always safe.',
      decision: 'Use Node.js’s built-in `node:sqlite` module through a single parameterised-query wrapper (`src/db/index.ts`).',
      consequences: 'No native modules to compile or audit; one file owns every SQL query, which is what makes the SAST rule against raw SQL concatenation possible.',
    },
    {
      title: 'Server-rendered pages plus a JSON API, not a separate front-end build',
      context: 'Fewer moving parts to secure (one CSP, one session mechanism, one CSRF story) and no separate build step for a small business owner to manage.',
      decision: 'EJS templates with auto-escaping for pages; the same route registry also serves JSON under `/api` for anything that needs it.',
      consequences: 'No client-side framework, no bundler, nothing to keep patched beyond the packages in package.json.',
    },
    {
      title: 'Secrets come from a seam, not from a bundled secret manager',
      context:
        'Secure by Design AC-05 asks for secrets in a secret manager with automatic rotation. This app usually runs on one person\u2019s computer, where a secret manager solves problems that do not exist: access control between people, audit of who read what, revocation across machines. Running one beside the app would add a service to unseal, back up and keep alive, and its own credential would end up in a file on the same disk with the same permissions as the .env file it replaced.',
      decision:
        'Keep the .env file with strict permissions as the default, and read every secret through one small seam (`src/lib/secrets.ts`) so a host\u2019s own store can supply them instead: a folder of files (Docker secrets, systemd credentials) supplied by whatever writes them there. Deliberately no \u201crun a command\u201d source: that would have every app start an operating-system command at boot, and SecureVibe\u2019s own scanner raised two high findings against the first version that had one. Tools like sops and Vault produce an environment or a file before the process starts, so nothing is lost. Values already in the environment always win. Rotate the session and token keys with `npm run rotate:keys`; the field-encryption key has its own script because it re-encrypts stored data.',
      consequences:
        'Moving to a hosted secret store needs configuration rather than code changes, which is what makes the deployment-time answer reachable instead of aspirational. AC-05 still reads "no" until secrets actually live in such a store and rotate automatically \u2014 a seam and a manual rotation command are real hardening, not the control itself, and recording them as one would overstate what the app does.',
    },
    {
      title: 'A hardened baseline that the AI only extends, never rewrites',
      context: 'Security controls implemented once, tested once, and evidenced mechanically are more trustworthy than controls re-generated by a language model for every app.',
      decision: 'Core security files (session, CSRF, headers, password, authorization, the route registry) are protected paths; the generator adds features that follow the same registry and conventions shown in `src/features/_example/`.',
      consequences: 'A generated app inherits every fix made to the baseline template; the compliance report can credit a control mechanically because the code that implements it did not change.',
    },
  ];
  return baseline.map((b, i) => ({
    file: `${String(i + 1).padStart(4, '0')}-${slug(b.title)}.md`,
    content: doc(`ADR ${i + 1}: ${b.title}`, 'Status: accepted (baseline template decision)', ['## Context', '', b.context, '', '## Decision', '', b.decision, '', '## Consequences', '', b.consequences].join('\n')),
  }));
}


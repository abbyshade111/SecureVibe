function genOpenApi(routes: RouteSummary[], schemas: ReturnType<typeof routeSchemasAsJson>): object {
  const byRoute = new Map(schemas.map((s) => [`${s.method} ${s.path}`, s]));
  const paths: Record<string, Record<string, unknown>> = {};
  for (const r of routes) {
    if (r.path.startsWith('/__securevibe')) continue;
    const p = pathToOpenApi(r.path);
    const s = byRoute.get(`${r.method} ${r.path}`);
    const parameters: unknown[] = [];
    for (const name of r.params) parameters.push({ name, in: 'path', required: true, schema: { type: 'string' } });
    if (s?.query && typeof s.query === 'object') parameters.push({ name: 'query', in: 'query', style: 'form', explode: true, schema: s.query });
    const operation: Record<string, unknown> = {
      summary: r.summary || `${r.method} ${r.path}`,
      tags: [r.kind],
      security: r.auth === 'public' ? [] : [{ sessionCookie: [] }],
      ...(parameters.length > 0 ? { parameters } : {}),
      ...(s?.body ? { requestBody: { required: true, content: { 'application/json': { schema: s.body } } } } : {}),
      responses: {
        '200': { description: 'Success' },
        ...(r.auth !== 'public' ? { '401': { description: 'Not signed in' }, '403': { description: 'Not allowed' } } : {}),
        '400': { description: 'The request did not pass validation' },
      },
    };
    paths[p] ??= {};
    paths[p]![r.method.toLowerCase()] = operation;
  }
  return {
    openapi: '3.1.0',
    info: { title: `${config.appName} API`, version: '1.0.0', description: 'Generated by npm run docs:build from the live route registry.' },
    servers: [{ url: '/' }],
    components: { securitySchemes: { sessionCookie: { type: 'apiKey', in: 'cookie', name: SESSION_COOKIE } } },
    paths,
  };
}

